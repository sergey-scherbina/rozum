#!/usr/bin/env python3
"""Render the latest benchmark results into RESULTS.md — and keep it honest.

    scripts/bench/render-results.py            # rewrite the generated block
    scripts/bench/render-results.py --check    # exit 1 if it is out of date
    scripts/bench/render-results.py --runs 5 --min-cells 10

WHY THIS EXISTS AND WHAT IT REFUSES TO DO

A results page is worth having only if updating it is cheaper than not updating it, so
this reads `results/*/per-run.csv` and rewrites one marked block. Everything outside the
markers is yours; everything inside is regenerated, so a hand edit there is lost — which
is the point, since a hand-maintained number is a number that silently goes stale.

Three things it deliberately does NOT do, each because doing it would produce a figure
that reads as fact and is not:

1. **No cross-run leaderboard.** Runs differ in binary, model set, host load and date.
   Merging them into one "best model" table would compare a measurement from March with
   one from August and present the difference as capability. Each run is reported as
   itself, with what it was measured on.
2. **No single blended pass rate across models.** `summarize_matrix.py` already refuses
   this for the same reason: a run mixes curated coders with probe models kept for
   context, and the average moves when the probe list changes rather than when anything
   got better. Per-model rows only.
3. **No timing where timing is meaningless.** A run that borrowed someone's gateway
   (`BENCH_GATEWAY_URL`) has contended seconds and an empty footprint column; those runs
   are labelled `shared` and their seconds are omitted, not printed with a caveat nobody
   reads.

The newest directory is often a one-cell verification run, so `--min-cells` (default 20)
decides what counts as a matrix worth reporting. Smaller runs are still listed, by name
and size, under "recent smaller runs" — present, not promoted.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS_DIR = HERE / "results"
DEFAULT_OUT = HERE / "RESULTS.md"

BEGIN = "<!-- BEGIN GENERATED by scripts/bench/render-results.py — do not edit by hand -->"
END = "<!-- END GENERATED -->"


class Run:
    """One result directory, read once."""

    def __init__(self, path: Path):
        self.path = path
        self.name = path.name
        self.rows: list[dict] = []
        csv_path = path / "per-run.csv"
        with csv_path.open() as fh:
            self.rows = [r for r in csv.DictReader(fh) if r.get("agent")]
        self.when = dt.datetime.fromtimestamp(csv_path.stat().st_mtime)
        # A run that borrowed a gateway leaves the footprint column empty on purpose (it
        # will not report a number for a process it does not own), and its seconds are
        # contended. That is the signal, and it is in the data rather than in a filename.
        self.shared = not any((r.get("model_footprint_mb") or "").strip() for r in self.rows)

    @property
    def cells(self) -> int:
        return len(self.rows)

    @property
    def models(self) -> list[str]:
        return sorted({r["model"] for r in self.rows if r.get("model")})

    @property
    def agents(self) -> list[str]:
        return sorted({r["agent"] for r in self.rows if r.get("agent")})

    @property
    def passed(self) -> int:
        return sum(1 for r in self.rows if r.get("pass") == "1")


def short_model(spec: str) -> str:
    """`mlx-community:Qwen3.5-4B-MLX-4bit` -> `Qwen3.5-4B-MLX-4bit`."""
    return spec.split(":")[-1] if spec else "?"


def load_runs() -> list[Run]:
    runs = []
    for csv_path in sorted(RESULTS_DIR.glob("*/per-run.csv")):
        try:
            run = Run(csv_path.parent)
        except (OSError, csv.Error):
            continue  # a truncated or unreadable run is skipped, not guessed at
        if run.cells:
            runs.append(run)
    runs.sort(key=lambda r: r.when, reverse=True)
    return runs


def matrix_table(run: Run) -> list[str]:
    """model × agent, pass/total per cell group, plus median seconds when they mean
    something."""
    by: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in run.rows:
        by[(r["model"], r["agent"])].append(r)
    agents = run.agents
    head = "| model | " + " | ".join(agents) + " |"
    rule = "|---|" + "---|" * len(agents)
    lines = [head, rule]
    for model in run.models:
        cells = []
        for agent in agents:
            group = by.get((model, agent), [])
            if not group:
                cells.append("—")
                continue
            ok = sum(1 for r in group if r.get("pass") == "1")
            cell = f"{ok}/{len(group)}"
            if not run.shared:
                secs = [float(r["seconds"]) for r in group if (r.get("seconds") or "").strip()]
                if secs:
                    cell += f" · {statistics.median(secs):.0f}s"
            cells.append(cell)
        lines.append(f"| `{short_model(model)}` | " + " | ".join(cells) + " |")
    return lines


def task_line(run: Run) -> str:
    """Which tasks a run covered, so a 5/5 on `greet` alone is not read as a 5/5."""
    by_task: dict[str, list[dict]] = defaultdict(list)
    for r in run.rows:
        by_task[r["task"]].append(r)
    parts = []
    for task in sorted(by_task, key=lambda t: (len(by_task[t]), t), reverse=True):
        group = by_task[task]
        ok = sum(1 for r in group if r.get("pass") == "1")
        parts.append(f"`{task}` {ok}/{len(group)}")
    return ", ".join(parts)


def render(runs: list[Run], n_runs: int, min_cells: int) -> str:
    big = [r for r in runs if r.cells >= min_cells]
    small = [r for r in runs if r.cells < min_cells]
    out: list[str] = [BEGIN, ""]
    out.append(
        f"_Generated from `scripts/bench/results/*/per-run.csv` — "
        f"{len(runs)} runs on disk, {len(big)} of them with ≥{min_cells} cells._"
    )
    out.append("")

    if not big:
        out.append("No run on disk has enough cells to report as a matrix.")
        out += ["", END]
        return "\n".join(out)

    for run in big[:n_runs]:
        kind = "shared gateway — pass/fail only" if run.shared else "own gateway"
        out.append(f"### {run.name}")
        out.append("")
        out.append(
            f"{run.when:%Y-%m-%d} · {run.cells} cells · {run.passed}/{run.cells} green · "
            f"{len(run.models)} models × {len(run.agents)} agents · _{kind}_"
        )
        out.append("")
        out += matrix_table(run)
        out.append("")
        out.append(f"By task: {task_line(run)}")
        out.append("")

    # The newest runs are often one model deep; the runs that actually compare MODELS are
    # wider and usually older. Sorting only by date hides exactly the tables someone came
    # here to read, so the widest ones get their own section — with their dates on show,
    # because they are not newer and must not read as if they were.
    widest = sorted(big, key=lambda r: (len(r.models) * len(r.agents), r.cells), reverse=True)
    widest = [r for r in widest if len(r.models) > 1][:2]
    shown = {r.name for r in big[:n_runs]}
    widest = [r for r in widest if r.name not in shown]
    if widest:
        out.append("### Widest matrices on disk")
        out.append("")
        out.append(
            "The runs that compare models against each other. Older than the ones above — "
            "dates are on each — and measured on their own binaries, so read each as itself."
        )
        out.append("")
        for run in widest:
            kind = "shared gateway — pass/fail only" if run.shared else "own gateway"
            out.append(f"#### {run.name}")
            out.append("")
            out.append(
                f"{run.when:%Y-%m-%d} · {run.cells} cells · {run.passed}/{run.cells} green · "
                f"{len(run.models)} models × {len(run.agents)} agents · _{kind}_"
            )
            out.append("")
            out += matrix_table(run)
            out.append("")

    if small:
        out.append("### Recent smaller runs")
        out.append("")
        out.append(
            "Single-cell verifications and spot checks — listed so they are visible, not "
            "promoted into the tables above."
        )
        out.append("")
        out.append("| run | when | cells | green |")
        out.append("|---|---|---|---|")
        for run in small[:10]:
            out.append(
                f"| `{run.name}` | {run.when:%Y-%m-%d} | {run.cells} | {run.passed} |"
            )
        out.append("")

    out.append(END)
    return "\n".join(out)


def splice(existing: str, block: str) -> str:
    """Replace the marked region, or append it if the file has none yet."""
    if BEGIN in existing and END in existing:
        head = existing.split(BEGIN)[0]
        tail = existing.split(END, 1)[1]
        return head + block + tail
    sep = "" if existing.endswith("\n\n") or not existing else "\n"
    return existing + sep + "\n" + block + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--runs", type=int, default=3, help="matrices to report (default 3)")
    ap.add_argument(
        "--min-cells",
        type=int,
        default=20,
        help="cells a run needs before it is reported as a matrix (default 20)",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the file is out of date",
    )
    args = ap.parse_args()

    if not RESULTS_DIR.is_dir():
        print(f"no results directory at {RESULTS_DIR}", file=sys.stderr)
        return 2

    runs = load_runs()
    block = render(runs, args.runs, args.min_cells)
    existing = args.out.read_text() if args.out.exists() else ""
    updated = splice(existing, block)

    if args.check:
        if existing != updated:
            print(
                f"{args.out} is out of date — run scripts/bench/render-results.py",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out} is current")
        return 0

    args.out.write_text(updated)
    reported = min(args.runs, len([r for r in runs if r.cells >= args.min_cells]))
    print(f"wrote {args.out} — {reported} matrices, {len(runs)} runs scanned")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
